export function describePhenomena(snapshot) {
  const { retrogradeBodies = [], aspects = [], moon } = snapshot;

  const retrogrades = retrogradeBodies
    .map((body) => {
      const data = RETROGRADE_PHENOMENA[body];
      if (!data) return null;
      return { type: 'retrograde', body, ...data };
    })
    .filter(Boolean);

  const activeAspects = aspects
    .slice()
    .sort((a, b) => a.orb - b.orb)
    .slice(0, 3)
    .map((aspect) => {
      const data = ASPECT_PHENOMENA[aspect.aspect];
      if (!data) return null;
      return {
        type: 'aspect',
        bodyA: aspect.bodyA,
        bodyB: aspect.bodyB,
        aspect: aspect.aspect,
        orb: aspect.orb,
        severity: getAspectSeverity(aspect.orb),
        ...data,
      };
    })
    .filter(Boolean);

  const moonPhase = moon?.name
    ? { type: 'moon-phase', phase: moon.name, ...MOON_PHASE_PHENOMENA[moon.name] }
    : null;

  return {
    date: snapshot.date,
    retrogrades,
    aspects: activeAspects,
    moon: moonPhase,
  };
}

export function getAspectSeverity(orb) {
  if (orb <= 0.5) return 'critical';
  if (orb <= 2) return 'elevated';
  if (orb <= 5) return 'moderate';
  return 'minor';
}